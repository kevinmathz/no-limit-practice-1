"""Amalgamate rt_eval, oppmodel, tvalue, postflop and core into one agent.py.

Each module is embedded as source and exec'd into its own module namespace (krd_<name>),
so private helper names never collide. Output:
  no-limit-practice-1/kevin_v1/agent.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = str(__import__("pathlib").Path(__file__).resolve().parents[2]) + "/kevin_v1/agent.py"
MODULES = ["rt_eval", "oppmodel", "tvalue", "postflop", "core"]


def rewrite(src):
    for m in MODULES:
        src = re.sub(rf"^(\s*)from {m} import", rf"\1from krd_{m} import", src, flags=re.M)
        src = re.sub(rf"^(\s*)import {m} as", rf"\1import krd_{m} as", src, flags=re.M)
    return src


def main():
    parts = ['"""KRD CFR bot (keep-reveal-discard). GENERATED by tmp/krd/build_agent.py - edit the',
             'sources there (core.py, tvalue.py, oppmodel.py, postflop.py, rt_eval.py) and rebuild.',
             '',
             'Choose: CFR-balanced keep/reveal mix. Short stacks: CFR push/fold chart + exact',
             'tournament-points EV (ICM / hand-cap horizon). Deep: equity vs reveal-conditioned',
             'ranges. Opponent model (reveal habits, jam/call rates) lives in `memory`.',
             '"""',
             'import os',
             'for _v in ("OMP_NUM_THREADS", "MKL_NUM_THREADS", "OPENBLAS_NUM_THREADS", "NUMBA_NUM_THREADS"):',
             '    os.environ.setdefault(_v, "1")',
             'import sys  # noqa: E402',
             'import types  # noqa: E402',
             '',
             '_SOURCES = {}']
    for m in MODULES:
        with open(os.path.join(HERE, m + ".py")) as f:
            src = rewrite(f.read())
        parts.append(f"_SOURCES[{('krd_' + m)!r}] = {src!r}")
    parts += [
        '',
        '',
        'def _load(name):',
        '    mod = types.ModuleType(name)',
        '    mod.__file__ = __file__',
        '    sys.modules[name] = mod',
        '    exec(compile(_SOURCES[name], "<" + name + ">", "exec"), mod.__dict__)',
        '    return mod',
        '',
        '',
        f'for _m in {["krd_" + m for m in MODULES]!r}:',
        '    _load(_m)',
        '',
        '_Core = sys.modules["krd_core"].Agent',
        '',
        '',
        '# Move every import-time object into the permanent GC generation: full collections',
        '# would otherwise rescan the tables and module objects and cause multi-ms pauses in act().',
        'import gc  # noqa: E402',
        'gc.collect()',
        'gc.freeze()',
        '',
        '',
        'class Agent(_Core):',
        '    def act(self, state, memory):',
        '        return _Core.act(self, state, memory)',
        '',
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(parts))
    print("wrote", OUT, os.path.getsize(OUT) // 1024, "KB")


if __name__ == "__main__":
    main()
